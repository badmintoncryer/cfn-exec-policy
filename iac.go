package main

import (
	"encoding/json"
	"fmt"
	"io"
	"strings"
	"unicode"
)

// identifier turns a policy name into a Terraform resource name or a CDK
// construct ID: "cfn-exec-policy-2" -> "cfn_exec_policy_2" / "CfnExecPolicy2".
func identifier(name string, camel bool) string {
	var b strings.Builder
	up := true
	for _, r := range name {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if camel && up {
				r = unicode.ToUpper(r)
			}
			b.WriteRune(r)
			up = false
		case !camel:
			b.WriteRune('_')
		default:
			up = true
		}
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "p" + s
	}
	return s
}

func indentJSON(d PolicyDocument, prefix string) string {
	b, _ := json.MarshalIndent(d, prefix, "  ")
	return string(b)
}

// WriteTerraform writes one aws_iam_policy per document, and their ARNs as an output.
func WriteTerraform(w io.Writer, names []string, docs []PolicyDocument) {
	fmt.Fprintf(w, "# Generated by cfn-exec-policy %s. Pass the ARNs to\n# cdk bootstrap --cloudformation-execution-policies.\n", version)
	var refs []string
	for i, d := range docs {
		id := identifier(names[i], false)
		// A heredoc interpolates ${ and %{; an IAM policy variable like ${aws:username} must stay literal.
		body := strings.NewReplacer("${", "$${", "%{", "%%{").Replace(indentJSON(d, "    "))
		fmt.Fprintf(w, "\nresource \"aws_iam_policy\" %q {\n  name   = %q\n  policy = <<-EOT\n    %s\n  EOT\n}\n", id, names[i], body)
		refs = append(refs, "aws_iam_policy."+id+".arn")
	}
	fmt.Fprintf(w, "\noutput \"cfn_exec_policy_arns\" {\n  value = [%s]\n}\n", strings.Join(refs, ", "))
}

// WriteCDK writes a TypeScript function that creates one ManagedPolicy per document.
func WriteCDK(w io.Writer, names []string, docs []PolicyDocument) {
	fmt.Fprintf(w, `// Generated by cfn-exec-policy %s. Pass the policies' ARNs to
// cdk bootstrap --cloudformation-execution-policies.
import * as iam from 'aws-cdk-lib/aws-iam';
import { Construct } from 'constructs';

export function cfnExecPolicies(scope: Construct): iam.ManagedPolicy[] {
  return [
`, version)
	for i, d := range docs {
		fmt.Fprintf(w, "    new iam.ManagedPolicy(scope, %q, {\n      managedPolicyName: %q,\n      document: iam.PolicyDocument.fromJson(%s),\n    }),\n",
			identifier(names[i], true), names[i], indentJSON(d, "      "))
	}
	fmt.Fprint(w, "  ];\n}\n")
}
